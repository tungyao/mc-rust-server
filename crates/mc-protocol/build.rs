//! mc-protocol build script: 从 `data/manifest.json` 生成 Configuration 阶段原版
//! registry_data 包体的有序索引（对应 `vanilla_config_777.rs` 的两个公开符号）。
//!
//! 文件名相对于 `data/<data_dir>/vanilla_config/`；生成 `$OUT_DIR/vanilla_config_generated.rs`。
//! 缺失文件、条目数 != 32、名字重复都会编译期 panic，不静默回退到旧硬编码。
use std::collections::HashSet;
use std::env;
use std::fs;
use std::path::PathBuf;

use serde_json::Value;

const EXPECTED_VERSION: &str = "26.3";
const EXPECTED_PROTOCOL: u64 = 777;
const EXPECTED_DATA_VERSION: u64 = 5023;
const EXPECTED_REGISTRIES: usize = 32;

fn main() {
    println!("cargo:rerun-if-changed=build.rs");

    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let data_root = manifest_dir.join("../../data");
    let manifest_path = data_root.join("manifest.json");
    println!("cargo:rerun-if-changed={}", manifest_path.display());

    let manifest = read_json(&manifest_path);
    assert_eq!(
        manifest.get("version").and_then(Value::as_str),
        Some(EXPECTED_VERSION),
        "data/manifest.json version mismatch"
    );
    assert_eq!(
        as_u64(manifest.get("protocol"), "manifest.protocol"),
        EXPECTED_PROTOCOL,
        "data/manifest.json protocol mismatch"
    );
    assert_eq!(
        as_u64(manifest.get("data_version"), "manifest.data_version"),
        EXPECTED_DATA_VERSION,
        "data/manifest.json data_version mismatch"
    );

    let data_dir = manifest
        .get("data_dir")
        .and_then(Value::as_str)
        .expect("manifest.data_dir must be a string");
    assert!(
        is_simple_name(data_dir),
        "manifest.data_dir must be a simple relative directory name"
    );

    let vanilla_dir = data_root.join(data_dir).join("vanilla_config");
    assert!(
        vanilla_dir.is_dir(),
        "vanilla_config directory missing: {}",
        vanilla_dir.display()
    );
    println!("cargo:rerun-if-changed={}", vanilla_dir.display());

    let config = manifest
        .get("vanilla_config")
        .and_then(Value::as_object)
        .expect("manifest.vanilla_config must be an object");
    let registries = config
        .get("registries")
        .and_then(Value::as_array)
        .expect("manifest.vanilla_config.registries must be an array");
    assert_eq!(
        registries.len(),
        EXPECTED_REGISTRIES,
        "vanilla_config.registries must contain exactly {EXPECTED_REGISTRIES} entries"
    );

    let mut seen = HashSet::new();
    let mut entries = String::new();
    for (i, entry) in registries.iter().enumerate() {
        let name = entry
            .get("name")
            .and_then(Value::as_str)
            .unwrap_or_else(|| panic!("vanilla_config.registries[{i}] missing `name`"));
        let file = entry
            .get("file")
            .and_then(Value::as_str)
            .unwrap_or_else(|| panic!("vanilla_config.registries[{i}] missing `file`"));
        assert!(!name.is_empty(), "vanilla_config.registries[{i}].name is empty");
        assert!(
            seen.insert(name),
            "duplicate registry name in vanilla_config.registries: {name}"
        );
        check_file(&vanilla_dir, file, &format!("vanilla_config.registries[{i}].file"));
        entries.push_str(&format!(
            "    ({}, {}),\n",
            rust_string(name),
            include_bytes_expr(data_dir, file)
        ));
    }

    let update_tags = config
        .get("update_tags")
        .and_then(Value::as_str)
        .expect("manifest.vanilla_config.update_tags must be a string");
    check_file(&vanilla_dir, update_tags, "vanilla_config.update_tags");

    let mut out = String::new();
    out.push_str("// @generated by crates/mc-protocol/build.rs — DO NOT EDIT.\n");
    out.push_str("// Source: data/manifest.json + data/<data_dir>/vanilla_config/*.bin\n\n");
    out.push_str("/// 32 个 registry_data 包体，顺序与原版 SYNCHRONIZED_REGISTRIES 一致。\n");
    out.push_str(
        "pub static VANILLA_CONFIG_REGISTRY_BODIES_777: &[(&str, &[u8])] = &[\n",
    );
    out.push_str(&entries);
    out.push_str("];\n\n");
    out.push_str("/// 同一次抓取的 Update Tags 0x0E 包体（15 个注册表）。\n");
    out.push_str("pub static VANILLA_CONFIG_UPDATE_TAGS_BODY_777: &[u8] =\n    ");
    out.push_str(&include_bytes_expr(data_dir, update_tags));
    out.push_str(";\n");

    let dest = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR"))
        .join("vanilla_config_generated.rs");
    fs::write(&dest, out).expect("write $OUT_DIR/vanilla_config_generated.rs");
}

fn read_json(path: &std::path::Path) -> Value {
    let text =
        fs::read_to_string(path).unwrap_or_else(|e| panic!("read {}: {e}", path.display()));
    serde_json::from_str(&text)
        .unwrap_or_else(|e| panic!("parse JSON {}: {e}", path.display()))
}

fn as_u64(v: Option<&Value>, ctx: &str) -> u64 {
    v.and_then(Value::as_u64)
        .unwrap_or_else(|| panic!("{ctx}: expected non-negative integer"))
}

/// 拒绝路径分隔符 / 父目录引用，避免 manifest 把 include_bytes! 指向目录外。
fn is_simple_name(name: &str) -> bool {
    !name.is_empty()
        && name != "."
        && name != ".."
        && name
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '-' || c == '.')
}

fn check_file(vanilla_dir: &std::path::Path, file: &str, ctx: &str) {
    assert!(is_simple_name(file), "{ctx}: not a simple file name: {file}");
    let path = vanilla_dir.join(file);
    assert!(path.is_file(), "{ctx}: file missing: {}", path.display());
}

fn include_bytes_expr(data_dir: &str, file: &str) -> String {
    format!(
        "include_bytes!(concat!(env!(\"CARGO_MANIFEST_DIR\"), \"/../../data/{data_dir}/vanilla_config/{file}\"))"
    )
}

/// 输出合法的 Rust 字符串字面量。
fn rust_string(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 2);
    out.push('"');
    for c in s.chars() {
        match c {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if c.is_control() => out.push_str(&format!("\\u{{{:x}}}", c as u32)),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}
